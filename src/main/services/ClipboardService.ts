import { randomUUID } from 'crypto';
import { clipboard as electronClipboard, safeStorage } from 'electron';
import type { PrismaClient } from 'generated/prisma/client';
import type { ClipboardEntryView, ClipboardSettings, ClipboardStatus } from '@shared/clipboard';

const MAX_TEXT_BYTES = 100 * 1024;
const POLL_MS = 750;

interface ClipboardApi {
  readText(): string | Promise<string>;
  writeText(text: string): void | Promise<void>;
  has?(format: string): boolean | Promise<boolean>;
  availableFormats?(): string[];
}

interface SecretStorage {
  isEncryptionAvailable(): boolean;
  encryptString(value: string): Buffer;
  decryptString(value: Buffer): string;
}

export interface ClipboardServiceDeps {
  getClient: () => PrismaClient | null;
  getConfig: () => ClipboardSettings;
  clipboard?: ClipboardApi;
  storage?: SecretStorage;
  now?: () => number;
  intervalMs?: number;
}

const CONCEALED_FORMATS = [
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.TransientType',
  'org.nspasteboard.AutoGeneratedType',
  'Clipboard Viewer Ignore',
  'ExcludeClipboardContentFromMonitorProcessing',
  'CanIncludeInClipboardHistory',
  'x-kde-passwordManagerHint',
];

interface SessionEntry {
  id: string;
  text: string;
  pinned: boolean;
  createdAt: number;
}

export class ClipboardService {
  private timer: ReturnType<typeof setInterval> | null = null;
  private lastText: string | null = null;
  private unreadable = 0;
  private lastPrune = 0;
  private session: SessionEntry[] = [];
  private readonly deps: ClipboardServiceDeps;

  constructor(deps: ClipboardServiceDeps) {
    this.deps = deps;
  }

  private clipboard(): ClipboardApi | null {
    return this.deps.clipboard ?? (electronClipboard as unknown as ClipboardApi);
  }

  private storage(): SecretStorage {
    return (
      this.deps.storage ?? {
        isEncryptionAvailable: () => safeStorage.isEncryptionAvailable(),
        encryptString: (value) => safeStorage.encryptString(value),
        decryptString: (value) => safeStorage.decryptString(value),
      }
    );
  }

  private now(): number {
    return this.deps.now?.() ?? Date.now();
  }

  private cutoff(): Date {
    return new Date(this.now() - this.deps.getConfig().retentionHours * 3_600_000);
  }

  private async pruneExisting(): Promise<void> {
    const client = this.deps.getClient();
    if (client) {
      await this.prune(client, this.deps.getConfig());
    }
    const cutoff = this.cutoff().getTime();
    this.session = this.session.filter((entry) => entry.pinned || entry.createdAt >= cutoff);
  }

  start(): void {
    if (this.timer) {
      return;
    }
    this.timer = setInterval(() => {
      const now = this.now();
      if (now - this.lastPrune > 10 * 60_000) {
        this.lastPrune = now;
        void this.pruneExisting().catch(() => undefined);
      }
      void this.poll().catch(() => undefined);
    }, this.deps.intervalMs ?? POLL_MS);
    this.timer.unref?.();
    void this.pruneExisting().catch(() => undefined);
  }

  stop(): void {
    if (this.timer) {
      clearInterval(this.timer);
      this.timer = null;
    }
  }

  private async concealed(api: ClipboardApi): Promise<boolean> {
    if (!api.has) {
      return false;
    }
    for (const format of CONCEALED_FORMATS) {
      try {
        if ((await api.has(format)) === true) {
          return true;
        }
      } catch {
        continue;
      }
    }
    return false;
  }

  async poll(): Promise<void> {
    const config = this.deps.getConfig();
    if (!config.enabled || config.paused) {
      return;
    }
    const api = this.clipboard();
    if (!api || (await this.concealed(api))) {
      return;
    }
    const raw = await api.readText();
    const text = typeof raw === 'string' ? raw.trim() : '';
    if (!text || Buffer.byteLength(text, 'utf8') > MAX_TEXT_BYTES) {
      return;
    }
    if (text === this.lastText) {
      return;
    }
    this.lastText = text;
    const client = this.deps.getClient();
    if (!client || !this.storage().isEncryptionAvailable()) {
      this.pushSession(text);
      return;
    }
    try {
      const existing = await client.clipboardEntry.findMany({ orderBy: { createdAt: 'desc' } });
      for (const row of existing) {
        try {
          if (this.storage().decryptString(Buffer.from(row.ciphertext, 'base64')) === text) {
            if (!row.pinned) {
              await client.clipboardEntry.update({ where: { id: row.id }, data: { createdAt: new Date(this.now()) } });
            }
            await this.prune(client, config).catch(() => undefined);
            return;
          }
        } catch {
          continue;
        }
      }
      const ciphertext = this.storage().encryptString(text).toString('base64');
      try {
        await client.clipboardEntry.create({ data: { ciphertext, createdAt: new Date(this.now()) } });
      } catch {
        this.pushSession(text);
        return;
      }
      await this.prune(client, config).catch(() => undefined);
    } catch {
      this.pushSession(text);
    }
  }

  private pushSession(text: string): void {
    const existing = this.session.find((entry) => !entry.pinned && entry.text === text);
    if (existing) {
      existing.createdAt = this.now();
      return;
    }
    this.session.unshift({ id: `session_${randomUUID()}`, text, pinned: false, createdAt: this.now() });
    const max = this.deps.getConfig().maxEntries;
    const pinned = this.session.filter((entry) => entry.pinned);
    const unpinned = this.session.filter((entry) => !entry.pinned).slice(0, max);
    this.session = [...pinned, ...unpinned].sort((left, right) => right.createdAt - left.createdAt);
  }

  private async prune(client: PrismaClient, config: ClipboardSettings): Promise<void> {
    const cutoff = new Date(this.now() - config.retentionHours * 3_600_000);
    await client.clipboardEntry.deleteMany({ where: { pinned: false, createdAt: { lt: cutoff } } });
    const rows = await client.clipboardEntry.findMany({ orderBy: { createdAt: 'desc' }, select: { id: true, pinned: true } });
    const drop = rows.filter((row) => !row.pinned).slice(config.maxEntries).map((row) => row.id);
    if (drop.length > 0) {
      await client.clipboardEntry.deleteMany({ where: { id: { in: drop } } });
    }
  }

  async list(query = ''): Promise<ClipboardEntryView[]> {
    const needle = query.trim().toLowerCase();
    const cutoff = this.cutoff().getTime();
    const entries: ClipboardEntryView[] = this.session
      .filter((entry) => (entry.pinned || entry.createdAt >= cutoff) && (!needle || entry.text.toLowerCase().includes(needle)))
      .map((entry) => ({
        id: entry.id,
        text: entry.text,
        pinned: entry.pinned,
        createdAt: new Date(entry.createdAt).toISOString(),
        sessionOnly: true,
      }));
    const client = this.deps.getClient();
    if (client) {
      const rows = await client.clipboardEntry.findMany({
        where: { OR: [{ pinned: true }, { createdAt: { gte: this.cutoff() } }] },
        orderBy: { createdAt: 'desc' },
      });
      this.unreadable = 0;
      for (const row of rows) {
        try {
          const text = this.storage().decryptString(Buffer.from(row.ciphertext, 'base64'));
          if (!needle || text.toLowerCase().includes(needle)) {
            entries.push({
              id: row.id,
              text,
              pinned: row.pinned,
              createdAt: row.createdAt.toISOString(),
              sessionOnly: false,
            });
          }
        } catch {
          this.unreadable += 1;
          continue;
        }
      }
    }
    return entries.sort((left, right) => right.createdAt.localeCompare(left.createdAt));
  }

  async setPinned(id: string, pinned: boolean): Promise<boolean> {
    if (id.startsWith('session_')) {
      const entry = this.session.find((row) => row.id === id);
      if (!entry) {
        return false;
      }
      entry.pinned = pinned;
      return true;
    }
    const client = this.deps.getClient();
    if (!client) {
      return false;
    }
    const result = await client.clipboardEntry.updateMany({ where: { id }, data: { pinned } });
    return result.count > 0;
  }

  async remove(id: string): Promise<boolean> {
    if (id.startsWith('session_')) {
      const before = this.session.length;
      this.session = this.session.filter((row) => row.id !== id);
      return this.session.length !== before;
    }
    const client = this.deps.getClient();
    if (!client) {
      return false;
    }
    const result = await client.clipboardEntry.deleteMany({ where: { id } });
    return result.count > 0;
  }

  async clear(): Promise<void> {
    this.session = [];
    const client = this.deps.getClient();
    if (client) {
      await client.clipboardEntry.deleteMany();
    }
  }

  async copy(id: string): Promise<boolean> {
    const entries = await this.list();
    const entry = entries.find((row) => row.id === id);
    const api = this.clipboard();
    if (!entry || !api) {
      return false;
    }
    await api.writeText(entry.text);
    this.lastText = entry.text;
    return true;
  }

  async status(): Promise<ClipboardStatus> {
    const config = this.deps.getConfig();
    const client = this.deps.getClient();
    const cutoff = this.cutoff();
    const count = client
      ? await client.clipboardEntry.count({ where: { OR: [{ pinned: true }, { createdAt: { gte: cutoff } }] } })
      : 0;
    const sessionCount = this.session.filter((entry) => entry.pinned || entry.createdAt >= cutoff.getTime()).length;
    let unreadable = 0;
    if (client) {
      const rows = await client.clipboardEntry.findMany({
        where: { OR: [{ pinned: true }, { createdAt: { gte: cutoff } }] },
        select: { ciphertext: true },
      });
      for (const row of rows) {
        try {
          this.storage().decryptString(Buffer.from(row.ciphertext, 'base64'));
        } catch {
          unreadable += 1;
        }
      }
    }
    return {
      encryptionAvailable: this.storage().isEncryptionAvailable(),
      enabled: config.enabled,
      paused: config.paused,
      count: count + sessionCount,
      sessionOnly: !this.storage().isEncryptionAvailable() || count === 0 && sessionCount > 0,
      unreadable,
    };
  }
}
