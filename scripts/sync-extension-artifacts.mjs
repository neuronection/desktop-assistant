#!/usr/bin/env node
// sync-extension-artifacts — embed the vendored family extension-contract
// artifacts (ADR-0040 / plan 32 Phase 8) as a TypeScript module the main
// process imports. The vendored JSON files at contracts/ stay the law —
// this script only wraps them verbatim (the manifest.schema.generated.ts
// precedent); a vendored copy is NEVER edited in-repo, drift is fixed by
// re-running dev/scripts/sync-extension-contract.sh.
//
// Usage:
//   node sync-extension-artifacts.mjs --ts <out.ts>
//   node sync-extension-artifacts.mjs --check <ts-path>
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, '..', 'contracts');

const ARTIFACTS = [
  ['EXTENSION_CHARTER', 'extension-charter.json'],
  ['ENVELOPE_SCHEMA', 'extension-manifest.schema.json'],
  ['SOURCES_SCHEMA', 'extension-sources.schema.json'],
];

function fail(code, message) {
  console.error(`sync-extension-artifacts: ${message}`);
  process.exit(code);
}

const embedded = ARTIFACTS.map(([name, file]) => {
  const path = join(contracts, file);
  if (!existsSync(path)) fail(2, `vendored artifact missing: ${path} — run dev/scripts/sync-extension-contract.sh`);
  const parsed = JSON.parse(readFileSync(path, 'utf8'));
  return { name, file, json: JSON.stringify(parsed, null, 2) };
});

const header = `// GENERATED by sync-extension-artifacts — do not edit.
// Verbatim embeddings of the vendored family artifacts (byte-identical law,
// dev/contracts canonical + scripts/sync-extension-contract.sh). Regenerate:
// node scripts/sync-extension-artifacts.mjs --ts src/shared/app-pack/extension.generated.ts
`;

const ts = `${header}${embedded
  .map(({ name, file, json }) => `export const ${name} = ${json} as const; // contracts/${file}`)
  .join('\n\n')}\n`;

const [, , mode, target] = process.argv;
if (mode === '--ts') {
  if (!target) fail(2, '--ts requires an output path');
  writeFileSync(target, ts, 'utf8');
  console.log(`sync-extension-artifacts: wrote ${target} (${embedded.map((e) => e.file).join(', ')})`);
} else if (mode === '--check') {
  if (!target) fail(2, '--check requires a path');
  if (!existsSync(target)) fail(1, `generated file missing: ${target}`);
  if (readFileSync(target, 'utf8') !== ts) {
    fail(1, `drift detected in ${target} — re-run dev/scripts/sync-extension-contract.sh, then node scripts/sync-extension-artifacts.mjs --ts ${target}`);
  }
  console.log('sync-extension-artifacts: no drift');
} else {
  fail(2, 'usage: sync-extension-artifacts.mjs --ts <out.ts> | --check <ts-path>');
}
