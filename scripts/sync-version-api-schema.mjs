#!/usr/bin/env node
// sync-version-api-schema.mjs — emit src/shared/updates/version-api.schema.generated.ts
// from the vendored family contract contracts/version-api.schema.json
// (ADR-0048 / plan 48). The generated module is what the updates service
// validates API responses against at runtime; the packaged app cannot read
// contracts/ (electron-builder `files`), so the schema rides the bundle.
//
// Usage:
//   node scripts/sync-version-api-schema.mjs          # regenerate
//   node scripts/sync-version-api-schema.mjs --check  # drift gate (exit 1 = stale)

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = join(root, 'contracts', 'version-api.schema.json');
const outFile = join(root, 'src', 'shared', 'updates', 'version-api.schema.generated.ts');

const args = new Set(process.argv.slice(2));
const check = args.has('--check');

const schema = JSON.parse(readFileSync(contractPath, 'utf8'));
const header =
  '// GENERATED by scripts/sync-version-api-schema.mjs from contracts/version-api.schema.json — DO NOT EDIT.\n';
const body = `${header}export const VERSION_API_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;\n`;

if (check) {
  const current = readFileSync(outFile, 'utf8');
  if (current !== body) {
    console.error('sync-version-api-schema: stale — run `node scripts/sync-version-api-schema.mjs`');
    process.exit(1);
  }
  console.log('sync-version-api-schema: up to date');
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, body);
  console.log('sync-version-api-schema: src/shared/updates/version-api.schema.generated.ts written');
}
