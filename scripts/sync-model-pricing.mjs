#!/usr/bin/env node
// sync-model-pricing — vendor the family model-pricing contract.
//
// Canonical: contracts/model-pricing.json + contracts/model-pricing.fixtures.json
// (beside this script's parent). P0 has an empty ledger and no product copy;
// P1 adds the desktop target. The generated TS is checked byte-for-byte, the
// vendored JSON/fixture pair is ledger-checked, and local edits are refused.
//
// Usage:
//   node scripts/sync-model-pricing.mjs --ts <out.ts>
//   node scripts/sync-model-pricing.mjs --check <out.ts>
//   node scripts/sync-model-pricing.mjs --sync [--project desktop-assistant] [--force]
//   node scripts/sync-model-pricing.mjs --check-vendored [--strict]
//   node scripts/sync-model-pricing.mjs --self-test
//
// Exit codes: 0 ok, 1 drift/pending in strict mode, 2 bad usage/canonical.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const DEV_ROOT = join(here, '..');
const WORKSPACE = join(DEV_ROOT, '..');
const SUPPORTED_SCHEMA = 1;

const TARGETS = [
  {
    repo: 'desktop-assistant',
    kind: 'desktop',
    contract: 'contracts/model-pricing.json',
    fixtures: 'tests/fixtures/model-pricing.fixtures.json',
    generated: 'src/shared/ai/modelPricing.generated.ts',
  },
  {
    repo: 'study-assistant',
    kind: 'py',
    module: 'backend/app/ai/model_pricing.py',
    data: 'backend/app/ai/model_pricing_data.py',
    fixtures: 'backend/tests/fixtures/model-pricing.fixtures.json',
  },
  {
    repo: 'career-assistant',
    kind: 'py',
    module: 'backend/app/ai/model_pricing.py',
    data: 'backend/app/ai/model_pricing_data.py',
    fixtures: 'backend/tests/fixtures/model-pricing.fixtures.json',
  },
  {
    repo: 'health-assistant/core',
    kind: 'py',
    module: 'backend/app/ai/model_pricing.py',
    data: 'backend/app/ai/model_pricing_data.py',
    fixtures: 'backend/tests/fixtures/model-pricing.fixtures.json',
  },
];

function fail(code, message) {
  console.error(`sync-model-pricing: ${message}`);
  process.exit(code);
}

function sha(text) {
  return createHash('sha256').update(text).digest('hex');
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    fail(2, `cannot read ${path}: ${error.message}`);
  }
}

function assertSupported(data) {
  if (data.schema !== SUPPORTED_SCHEMA) {
    throw new Error(`schema ${data.schema} not supported (supported: ${SUPPORTED_SCHEMA}) — extend the emitters first.`);
  }
  if (data.contract !== 'model-pricing') {
    throw new Error(`contract must be model-pricing, got ${data.contract}`);
  }
}

function loadCanonical(paths) {
  const data = readJson(paths.canonical);
  try {
    assertSupported(data);
  } catch (error) {
    fail(2, error.message);
  }
  return data;
}

function generateTs(data) {
  const rows = JSON.stringify(data.models ?? [], null, 2);
  const exceptions = JSON.stringify(data.coverageExceptions ?? [], null, 2);
  return `// GENERATED by sync-model-pricing.mjs from contracts/model-pricing.json (schema ${data.schema}) — DO NOT EDIT.
// Canonical: the family contract; regenerate with the sync script, never hand-edit.

export const MODEL_PRICING_SCHEMA = ${data.schema};

export const MODEL_PRICING_COMPILED = ${JSON.stringify(data.compiled)};

export interface ModelPricingMatch {
  exact: string[];
  prefix: string[];
  aliases: string[];
}

export interface ModelPricingRow {
  provider: string;
  match: ModelPricingMatch;
  inputMicrosPerMillion: number;
  outputMicrosPerMillion: number;
  metering: 'tokens' | 'input_only' | 'output_only';
  basis: 'list' | 'free';
  reviewed: string;
  source: string;
  retiredAt: string | null;
}

export interface ModelPricingCoverageException {
  provider: string;
  model: string;
  reason: 'local' | 'free_tier' | 'not_token_metered' | 'not_priced' | 'routing_alias';
  note: string;
  source?: string;
  reviewed?: string;
}

export const MODEL_PRICING_ROWS: ModelPricingRow[] = ${rows};

export const MODEL_PRICING_COVERAGE_EXCEPTIONS: ModelPricingCoverageException[] = ${exceptions};
`;
}

function pyLiteral(value, indent = 0) {
  const pad = ' '.repeat(indent);
  const childPad = ' '.repeat(indent + 2);
  if (value === null || value === undefined) return 'None';
  if (typeof value === 'boolean') return value ? 'True' : 'False';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return JSON.stringify(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${value.map((entry) => `${childPad}${pyLiteral(entry, indent + 2)},`).join('\n')}\n${pad}]`;
  }
  const entries = Object.entries(value).sort(([a], [b]) => a.localeCompare(b));
  if (entries.length === 0) return '{}';
  return `{\n${entries.map(([key, entry]) => `${childPad}${JSON.stringify(key)}: ${pyLiteral(entry, indent + 2)},`).join('\n')}\n${pad}}`;
}

function generatePyData(data) {
  return `# GENERATED by sync-model-pricing.mjs from contracts/model-pricing.json (schema ${data.schema}) — DO NOT EDIT.
# Canonical: the family contract; regenerate with the sync script, never hand-edit.
# Pure data: no imports, so the reference resolver stays import-free when vendored.

MODEL_PRICING_SCHEMA = ${data.schema}

MODEL_PRICING_COMPILED = ${JSON.stringify(data.compiled)}

MODEL_PRICING_ROWS = ${pyLiteral(data.models ?? [])}

MODEL_PRICING_COVERAGE_EXCEPTIONS = ${pyLiteral(data.coverageExceptions ?? [])}
`;
}

function targetPaths(root, target) {
  if (target.kind === 'py') {
    return {
      module: join(root, target.repo, target.module),
      data: join(root, target.repo, target.data),
      fixtures: join(root, target.repo, target.fixtures),
    };
  }
  return {
    contract: join(root, target.repo, target.contract),
    fixtures: join(root, target.repo, target.fixtures),
    generated: join(root, target.repo, target.generated),
  };
}

function ledgerRead(path) {
  const map = new Map();
  if (!existsSync(path)) return map;
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const parts = trimmed.split(':');
    if (parts.length < 3) continue;
    const key = `${parts[0]}:${parts.slice(1, -1).join(':')}`;
    map.set(key, parts[parts.length - 1]);
  }
  return map;
}

function ledgerWrite(path, map) {
  const body = [...map.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `${key}:${value}`)
    .join('\n');
  writeFileSync(path, body ? `${body}\n` : '');
}

function copyIfAllowed(source, destination, key, ledger, force) {
  const canonical = readFileSync(source, 'utf8');
  const canonicalSha = sha(canonical);
  if (!existsSync(destination)) {
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, canonical);
    ledger.set(key, canonicalSha);
    return 'adopted';
  }
  const current = readFileSync(destination, 'utf8');
  const currentSha = sha(current);
  if (currentSha === canonicalSha) {
    ledger.set(key, canonicalSha);
    return 'in-sync';
  }
  const last = ledger.get(key);
  if (last && currentSha === last) {
    writeFileSync(destination, canonical);
    ledger.set(key, canonicalSha);
    return 'synced';
  }
  if (force) {
    writeFileSync(destination, canonical);
    ledger.set(key, canonicalSha);
    return 'forced';
  }
  throw new Error(`REFUSED ${key}: local edits (sha ${currentSha.slice(0, 12)}, last-synced ${(last ?? 'never').slice(0, 12)})`);
}

function writeIfAllowed(content, destination, key, ledger, force) {
  const canonicalSha = sha(content);
  if (!existsSync(destination)) {
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, content);
    ledger.set(key, canonicalSha);
    return 'adopted';
  }
  const current = readFileSync(destination, 'utf8');
  const currentSha = sha(current);
  if (currentSha === canonicalSha) {
    ledger.set(key, canonicalSha);
    return 'in-sync';
  }
  const last = ledger.get(key);
  if (last && currentSha === last) {
    writeFileSync(destination, content);
    ledger.set(key, canonicalSha);
    return 'synced';
  }
  if (force) {
    writeFileSync(destination, content);
    ledger.set(key, canonicalSha);
    return 'forced';
  }
  throw new Error(`REFUSED ${key}: local edits (sha ${currentSha.slice(0, 12)}, last-synced ${(last ?? 'never').slice(0, 12)})`);
}

function syncTarget(root, target, paths, force) {
  const ledger = ledgerRead(paths.ledger);
  const destination = targetPaths(root, target);
  const data = loadCanonical(paths);
  const fixturesKey = `${target.repo}:${target.fixtures}`;

  if (target.kind === 'py') {
    const state = {
      module: copyIfAllowed(
        join(paths.devContracts, 'model_pricing.py'),
        destination.module,
        `${target.repo}:${target.module}`,
        ledger,
        force,
      ),
      data: writeIfAllowed(
        generatePyData(data),
        destination.data,
        `${target.repo}:${target.data}`,
        ledger,
        force,
      ),
      fixtures: copyIfAllowed(paths.fixtures, destination.fixtures, fixturesKey, ledger, force),
    };
    ledgerWrite(paths.ledger, ledger);
    return state;
  }

  const state = {
    contract: copyIfAllowed(
      paths.canonical,
      destination.contract,
      `${target.repo}:${target.contract}`,
      ledger,
      force,
    ),
    fixtures: copyIfAllowed(paths.fixtures, destination.fixtures, fixturesKey, ledger, force),
  };
  mkdirSync(dirname(destination.generated), { recursive: true });
  writeFileSync(destination.generated, generateTs(data));
  ledgerWrite(paths.ledger, ledger);
  return state;
}

function compareFile(source, destination, label, missing, drift) {
  if (!existsSync(destination)) {
    missing.push(label);
  } else if (readFileSync(source, 'utf8') !== readFileSync(destination, 'utf8')) {
    drift.push(label);
  }
}

function compareContent(content, destination, label, missing, drift) {
  if (!existsSync(destination)) {
    missing.push(label);
  } else if (readFileSync(destination, 'utf8') !== content) {
    drift.push(label);
  }
}

function checkTarget(root, target, paths) {
  const data = loadCanonical(paths);
  const destination = targetPaths(root, target);
  const missing = [];
  const drift = [];

  if (target.kind === 'py') {
    compareFile(
      join(paths.devContracts, 'model_pricing.py'),
      destination.module,
      'module',
      missing,
      drift,
    );
    compareContent(generatePyData(data), destination.data, 'data', missing, drift);
    compareFile(paths.fixtures, destination.fixtures, 'fixtures', missing, drift);
    return { missing, drift };
  }

  compareFile(paths.canonical, destination.contract, 'contract', missing, drift);
  compareFile(paths.fixtures, destination.fixtures, 'fixtures', missing, drift);
  compareContent(generateTs(data), destination.generated, 'generated', missing, drift);
  return { missing, drift };
}

function selfTest() {
  const root = mkdtempSync(join(tmpdir(), 'model-pricing-'));
  try {
    const canonicalDir = join(root, 'dev', 'contracts');
    mkdirSync(canonicalDir, { recursive: true });
    const canonical = join(canonicalDir, 'model-pricing.json');
    const fixtures = join(canonicalDir, 'model-pricing.fixtures.json');
    const ledger = join(canonicalDir, 'model-pricing.sync.json');
    writeFileSync(canonical, JSON.stringify({
      schema: 1, contract: 'model-pricing', currency: 'USD',
      unit: 'micros_per_million_tokens', compiled: '2026-11-11',
      coverageExceptions: [], models: [],
    }, null, 2));
    writeFileSync(fixtures, JSON.stringify({ schema: 1, contract: 'model-pricing-fixtures', cases: [] }, null, 2));
    writeFileSync(ledger, '');
    const target = { repo: 'product', contract: 'contracts/model-pricing.json', fixtures: 'tests/fixtures/model-pricing.fixtures.json', generated: 'src/shared/ai/modelPricing.generated.ts' };
    const paths = { canonical, fixtures, ledger };

    let check = checkTarget(root, target, paths);
    if (check.missing.length !== 3 || check.drift.length !== 0) throw new Error('self-test: pending expected');

    const first = syncTarget(root, target, paths, false);
    if (first.contract !== 'adopted' || first.fixtures !== 'adopted') throw new Error('self-test: adopt expected');
    check = checkTarget(root, target, paths);
    if (check.missing.length || check.drift.length) throw new Error('self-test: in-sync expected');

    const dest = targetPaths(root, target);
    writeFileSync(dest.contract, '{"local":true}\n');
    if (checkTarget(root, target, paths).drift.length !== 1) throw new Error('self-test: drift expected');
    let refused = false;
    try { syncTarget(root, target, paths, false); } catch { refused = true; }
    if (!refused) throw new Error('self-test: local-edit refusal expected');
    const forced = syncTarget(root, target, paths, true);
    if (forced.contract !== 'forced') throw new Error('self-test: force expected');

    let schemaRefused = false;
    try { assertSupported({ schema: 2, contract: 'model-pricing' }); } catch { schemaRefused = true; }
    if (!schemaRefused) throw new Error('self-test: unknown schema must be refused');
    console.log('sync-model-pricing: self-test OK');
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

const args = process.argv.slice(2);
const mode = args[0];
function findFixtures() {
  for (const candidate of [
    join(DEV_ROOT, 'contracts', 'model-pricing.fixtures.json'),
    join(DEV_ROOT, 'tests', 'fixtures', 'model-pricing.fixtures.json'),
  ]) {
    if (existsSync(candidate)) {
      return candidate;
    }
  }
  return join(DEV_ROOT, 'contracts', 'model-pricing.fixtures.json');
}

const paths = {
  canonical: join(DEV_ROOT, 'contracts', 'model-pricing.json'),
  fixtures: findFixtures(),
  devContracts: join(DEV_ROOT, 'contracts'),
  ledger: join(DEV_ROOT, 'contracts', 'model-pricing.sync.json'),
};

if (mode === '--py-data') {
  if (!args[1]) fail(1, '--py-data requires an output path');
  writeFileSync(args[1], generatePyData(loadCanonical(paths)));
  console.log(`sync-model-pricing: wrote ${args[1]}`);
} else if (mode === '--check-py-data') {
  if (!args[1]) fail(1, '--check-py-data requires the generated Python data path');
  const current = existsSync(args[1]) ? readFileSync(args[1], 'utf8') : '';
  if (current !== generatePyData(loadCanonical(paths))) {
    fail(1, `drift: ${args[1]} does not match contracts/model-pricing.json — regenerate`);
  }
  console.log('sync-model-pricing: no py-data drift');
} else if (mode === '--ts') {
  if (!args[1]) fail(1, '--ts requires an output path');
  writeFileSync(args[1], generateTs(loadCanonical(paths)));
  console.log(`sync-model-pricing: wrote ${args[1]}`);
} else if (mode === '--check') {
  if (!args[1]) fail(1, '--check requires the generated TS path');
  const current = existsSync(args[1]) ? readFileSync(args[1], 'utf8') : '';
  if (current !== generateTs(loadCanonical(paths))) {
    fail(1, `drift: ${args[1]} does not match contracts/model-pricing.json — regenerate`);
  }
  console.log('sync-model-pricing: no drift');
} else if (mode === '--sync') {
  const projectIndex = args.indexOf('--project');
  const project = projectIndex >= 0 ? args[projectIndex + 1] : null;
  const force = args.includes('--force');
  const selected = project ? TARGETS.filter((target) => target.repo === project) : TARGETS;
  if (!selected.length) fail(2, `unknown project: ${project}`);
  for (const target of selected) {
    const result = syncTarget(WORKSPACE, target, paths, force);
    const summary = Object.entries(result).map(([key, value]) => `${key}=${value}`).join(' ');
    console.log(`sync-model-pricing: ${target.repo} ${summary}`);
  }
} else if (mode === '--check-vendored') {
  const strict = args.includes('--strict');
  const projectIndex = args.indexOf('--project');
  const project = projectIndex >= 0 ? args[projectIndex + 1] : null;
  const selected = project ? TARGETS.filter((target) => target.repo === project) : TARGETS;
  if (!selected.length) fail(2, `unknown project: ${project}`);
  let failed = false;
  for (const target of selected) {
    const result = checkTarget(WORKSPACE, target, paths);
    if (result.missing.length) {
      console.log(`pending ${target.repo}: ${result.missing.join(', ')}`);
      if (strict) failed = true;
    }
    if (result.drift.length) {
      console.log(`drift ${target.repo}: ${result.drift.join(', ')}`);
      failed = true;
    }
    if (!result.missing.length && !result.drift.length) {
      console.log(`in-sync ${target.repo}`);
    }
  }
  if (failed) process.exit(1);
} else if (mode === '--self-test') {
  selfTest();
} else {
  console.log('usage: sync-model-pricing.mjs --ts <out.ts> | --check <out.ts> | --py-data <out.py> | --check-py-data <out.py> | --sync [--project <repo>] [--force] | --check-vendored [--project <repo>] [--strict] | --self-test');
  fail(1, 'missing mode');
}
