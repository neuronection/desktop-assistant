import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outDir = join(root, 'node_modules', '.tmp', 'ipc-codegen');
const check = process.argv.includes('--check');

const DOCS_PATH = join(root, 'docs/dev/ipc.md');
const PRELOAD_PATH = join(root, 'src/preload/preload.generated.ts');

const PRELOAD_HEADER = `// GENERATED by generate-ipc — do not edit.
// Source: src/shared/ipc/registry.ts
// Regenerate: node scripts/generate-ipc.mjs
//
// A sandboxed preload may only require('electron'). This module is compiled
// verbatim (no bundler), so it stays one file with no relative imports and
// no runtime dependencies — anything else leaves window.electronAPI
// undefined in packaged builds.

import { contextBridge, ipcRenderer } from 'electron';

type BridgeKind = 'invoke' | 'send' | 'on';
`;

async function transpile(sourcePath, outName, rewrite = []) {
  let source = await readFile(sourcePath, 'utf8');
  for (const [from, to] of rewrite) {
    source = source.replaceAll(from, to);
  }
  const output = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
    },
    fileName: sourcePath,
  }).outputText;
  const outPath = join(outDir, outName);
  await writeFile(outPath, output);
  return outPath;
}

function renderPreload(registry) {
  const rows = registry
    .filter((entry) => entry.bridge)
    .map((entry) => `  ['${entry.channel}', '${entry.bridge.method}', '${entry.bridge.kind}'],`);
  return [
    PRELOAD_HEADER,
    'const BRIDGE_ENTRIES: ReadonlyArray<readonly [channel: string, method: string, kind: BridgeKind]> = [',
    ...rows,
    '];',
    '',
    'export function createPreloadApi(): Record<string, unknown> {',
    '  const api: Record<string, unknown> = {};',
    '  for (const [channel, method, kind] of BRIDGE_ENTRIES) {',
    "    if (kind === 'on') {",
    '      api[method] = (callback: (payload?: unknown) => void): (() => void) => {',
    '        const handler = (_event: unknown, payload: unknown): void => callback(payload);',
    '        ipcRenderer.on(channel, handler);',
    '        return () => {',
    '          ipcRenderer.removeListener(channel, handler);',
    '        };',
    '      };',
    "    } else if (kind === 'send') {",
    '      api[method] = (...args: unknown[]) => ipcRenderer.send(channel, ...args);',
    '    } else {',
    '      api[method] = (...args: unknown[]) => ipcRenderer.invoke(channel, ...args);',
    '    }',
    '  }',
    '  return api;',
    '}',
    '',
    "contextBridge.exposeInMainWorld('electronAPI', createPreloadApi());",
    '',
  ].join('\n');
}

async function emit(path, content) {
  if (!check) {
    await writeFile(path, content);
    return true;
  }
  let current = '';
  try {
    current = await readFile(path, 'utf8');
  } catch {
    current = '';
  }
  return current === content;
}

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
await transpile(join(root, 'src/shared/speech.ts'), 'speech.mjs');
await transpile(join(root, 'src/shared/ipc/registry.ts'), 'registry.mjs', [
  ["from '@shared/speech'", "from './speech.mjs'"],
]);
const docsPath = await transpile(join(root, 'src/shared/ipc/docs.ts'), 'docs.mjs', [
  ["from './registry'", "from './registry.mjs'"],
]);
const { renderIpcDocs } = await import(pathToFileURL(docsPath).href);
const { IPC_REGISTRY } = await import(pathToFileURL(join(outDir, 'registry.mjs')).href);

const docsOk = await emit(DOCS_PATH, renderIpcDocs());
const preloadOk = await emit(PRELOAD_PATH, renderPreload(IPC_REGISTRY));

if (!check) {
  console.log('generated docs/dev/ipc.md and src/preload/preload.generated.ts');
} else if (!docsOk || !preloadOk) {
  const drifted = [!docsOk && 'docs/dev/ipc.md', !preloadOk && 'src/preload/preload.generated.ts'].filter(Boolean);
  console.error(`stale generated IPC projections: ${drifted.join(', ')}`);
  console.error('run `node scripts/generate-ipc.mjs` and commit the diff');
  process.exit(1);
} else {
  console.log('generated IPC projections are current');
}
