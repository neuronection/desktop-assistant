#!/usr/bin/env node
// sync-app-pack-contract — generate the mini-app pack contract module from the
// canonical JSON (single source, ADR-0029 / plan 26 S1).
// Master: dev/scripts/sync-app-pack-contract.mjs (vendored copies stay
// byte-identical). Reads contracts/mini-app-packs.json NEXT TO ITSELF.
//
// Usage:
//   node sync-app-pack-contract.mjs --ts <out.ts>     write the TypeScript module
//   node sync-app-pack-contract.mjs --check <ts-path> compare generated TS to disk (exit 1 on drift)
// Unknown "schema" versions are refused (exit 2).

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const canonicalPath = join(here, '..', 'contracts', 'mini-app-packs.json');

const SUPPORTED_SCHEMA = 1;

function fail(code, message) {
  console.error(`sync-app-pack-contract: ${message}`);
  process.exit(code);
}

if (!existsSync(canonicalPath)) {
  fail(2, `canonical file not found at ${canonicalPath}`);
}
const data = JSON.parse(readFileSync(canonicalPath, 'utf8'));
if (data.schema !== SUPPORTED_SCHEMA || data.contract !== 'mini-app-packs') {
  fail(2, `unsupported contract file (schema ${data.schema}, contract ${data.contract})`);
}

const capIds = data.capabilities.map((c) => c.id);
if (new Set(capIds).size !== capIds.length) fail(2, 'duplicate capability ids');
const slotIds = data.slots.taxonomy.map((s) => s.id);
if (new Set(slotIds).size !== slotIds.length) fail(2, 'duplicate slot ids');

function list(name, value) {
  if (!Array.isArray(value) || value.length === 0 || !value.every((v) => typeof v === 'string')) {
    fail(2, `${name} must be a non-empty string array`);
  }
  return value;
}

const caps = data.capabilities.map((c) => {
  if (!Array.isArray(c.tiers) || !c.tiers.every((t) => typeof t === 'number')) {
    fail(2, `capability ${c.id} tiers must be a number array`);
  }
  return { id: c.id, tiers: c.tiers };
});

const leafOps = list('composeOperators.leafOps', data.pipeline.composeOperators.leafOps);
const composites = list('composeOperators.conditions', data.pipeline.composeOperators.conditions).filter((c) => c !== 'leaf');

const sharedFields = data.envelopeSharedFields ?? {};
const categories = list('envelopeSharedFields.categoriesVocabulary', sharedFields.categoriesVocabulary);
const docsPointer = sharedFields.docsPointer;
if (typeof docsPointer !== 'string' || docsPointer.length === 0) {
  fail(2, 'envelopeSharedFields.docsPointer must be a non-empty string');
}
const repositoryPattern = '^https://[A-Za-z0-9][A-Za-z0-9.-]*[A-Za-z0-9](:[0-9]{1,5})?(/[^\\s@\\\\]*)?$';

const ts = `// GENERATED by sync-app-pack-contract — do not edit.
// Source: contracts/mini-app-packs.json (family canonical: dev/contracts/).
// Regenerate: node scripts/sync-app-pack-contract.mjs --ts src/shared/app-pack/contract.generated.ts

export const PACK_API_VERSION = ${data.apiVersion.current} as const;
export const PACK_DEPRECATION_WINDOW_MAJORS = ${data.apiVersion.deprecationWindowMajors} as const;

export const PACK_KINDS = ${JSON.stringify(list('identity.kind', Object.keys(data.identity.kind)))} as const;
export const PACK_ID_PATTERN = ${JSON.stringify(data.identity.idPattern)};
export const PACK_VERSION_PATTERN = ${JSON.stringify(data.identity.versionPattern)};
export const PACK_RESERVED_ID_PREFIXES = ${JSON.stringify(list('identity.reservedIdPrefixes', data.identity.reservedIdPrefixes))} as const;

export const PACK_CATEGORIES = ${JSON.stringify(categories)} as const;
export const PACK_DOCS_POINTER = ${JSON.stringify(docsPointer)};
export const PACK_REPOSITORY_PATTERN = ${JSON.stringify(repositoryPattern)};

export const PACK_CAPABILITIES = ${JSON.stringify(capIds)} as const;
export const PACK_CAPABILITY_TIERS: Readonly<Record<string, readonly number[]>> = {
${caps.map((c) => `  ${JSON.stringify(c.id)}: ${JSON.stringify(c.tiers)},`).join('\n')}
};

export const PACK_SLOTS = ${JSON.stringify(slotIds)} as const;

export const PACK_STEPS = ${JSON.stringify(list('pipeline.steps', data.pipeline.steps))} as const;
export const PACK_PROPOSE_VERBS = ${JSON.stringify(list('pipeline.proposeVerbs', data.pipeline.proposeVerbs))} as const;
export const PACK_VERDICTS = ${JSON.stringify(list('pipeline.verdicts', data.pipeline.verdicts))} as const;
export const PACK_QUESTION_TYPES = ${JSON.stringify(list('pipeline.questions', data.pipeline.questions))} as const;
export const PACK_RUN_STATUSES = ${JSON.stringify(list('pipeline.run.statuses', data.pipeline.run.statuses))} as const;
export const PACK_RUN_EVENTS = ${JSON.stringify(list('pipeline.run.events', data.pipeline.run.events))} as const;
export const PACK_ITEM_STATES = ${JSON.stringify(list('pipeline.run.itemStates', data.pipeline.run.itemStates))} as const;
export const PACK_CONDITION_COMPOSITES = ${JSON.stringify(composites)} as const;
export const PACK_LEAF_OPS = ${JSON.stringify(leafOps)} as const;

export const PACK_REPORT_COMPONENTS = ${JSON.stringify(list('report.components', data.report.components))} as const;
export const PACK_RUN_ACTIONS = ${JSON.stringify(list('report.actions.run', data.report.actions.run))} as const;
export const PACK_ITEM_ACTIONS = ${JSON.stringify(list('report.actions.item', data.report.actions.item))} as const;
export const PACK_EXPORT_FORMATS = ${JSON.stringify(list('report.exportFormats', data.report.exportFormats))} as const;

export const PACK_LIVE_CARD_COMPONENTS = ${JSON.stringify(list('liveCard.components', data.liveCard.components))} as const;
export const PACK_LIVE_CARD_BINDS = ${JSON.stringify(list('liveCard.binds', data.liveCard.binds))} as const;

export const PACK_ERROR_CODES = ${JSON.stringify(data.errors.codes.map((e) => e.code))} as const;

export const PACK_HOST_SENSITIVE_BASELINE = ${JSON.stringify(list('privacy.hostBaselineGlobs', data.privacy.hostBaselineGlobs))} as const;

export const PACK_REFUSED_ROOTS_EXACT = ${JSON.stringify(data.fs.refusedRoots.exact)} as const;
export const PACK_REFUSED_ROOTS_PREFIX = ${JSON.stringify(data.fs.refusedRoots.prefix)} as const;

export const PACK_LIMITS = ${JSON.stringify(data.limits, null, 2)} as const;
`;

const [, , mode, target, target2] = process.argv;
if (mode === '--ts') {
  if (!target) fail(2, '--ts requires an output path');
  writeFileSync(target, ts, 'utf8');
  console.log(`sync-app-pack-contract: wrote ${target} (${capIds.length} capabilities, ${slotIds.length} slots)`);
} else if (mode === '--check') {
  if (!target) fail(2, '--check requires a path');
  if (!existsSync(target)) fail(1, `generated file missing: ${target}`);
  const onDisk = readFileSync(target, 'utf8');
  if (onDisk !== ts) {
    fail(1, `drift detected in ${target} — regenerate with: node scripts/sync-app-pack-contract.mjs --ts ${target}`);
  }
  console.log('sync-app-pack-contract: no drift');
} else if (mode === '--schema') {
  if (!target) fail(2, '--schema requires an output path');
  writeFileSync(target, JSON.stringify(buildManifestSchema(data), null, 2) + '\n', 'utf8');
  console.log(`sync-app-pack-contract: wrote manifest schema ${target}`);
} else if (mode === '--schema-ts') {
  if (!target) fail(2, '--schema-ts requires an output path');
  writeFileSync(target, schemaTs(data), 'utf8');
  console.log(`sync-app-pack-contract: wrote manifest schema module ${target}`);
} else if (mode === '--check-schema') {
  if (!target || !target2) fail(2, '--check-schema requires <schema.json> <schema.ts>');
  const schemaJson = JSON.stringify(buildManifestSchema(data), null, 2) + '\n';
  const schemaModule = schemaTs(data);
  if (!existsSync(target) || !existsSync(target2)) fail(1, 'generated file missing');
  if (readFileSync(target, 'utf8') !== schemaJson || readFileSync(target2, 'utf8') !== schemaModule) {
    fail(1, `drift detected — regenerate with: node scripts/sync-app-pack-contract.mjs --schema ${target} && node scripts/sync-app-pack-contract.mjs --schema-ts ${target2}`);
  }
  console.log('sync-app-pack-contract: schema no drift');
} else {
  fail(2, 'usage: sync-app-pack-contract.mjs --ts <out.ts> | --check <ts-path> | --schema <out.json> | --schema-ts <out.ts> | --check-schema <json> <ts>');
}

function schemaTs(data) {
  return `// GENERATED by sync-app-pack-contract — do not edit.
// Source: contracts/mini-app-packs.json (family canonical: dev/contracts/).
// Regenerate: node scripts/sync-app-pack-contract.mjs --schema-ts src/shared/app-pack/manifest.schema.generated.ts

export const MANIFEST_SCHEMA = ${JSON.stringify(buildManifestSchema(data), null, 2)} as const;
`;
}

function buildManifestSchema(data) {
  const importedCaps = caps.filter((c) => c.tiers.includes(0)).map((c) => c.id);
  const allCapIds = caps.map((c) => c.id);
  const apiMin = data.apiVersion.current - data.apiVersion.deprecationWindowMajors + 1;
  const NODE_ID_PATTERN = '^[a-z][a-z0-9-]{0,39}$';
  const LOCALE_PATTERN = '^[a-z]{2,3}(-[A-Za-z0-9]{2,8})?$';

  const conditionNode = { type: 'object', $comment: `Composite conditions (all/any/not) over leaf ops (${data.pipeline.composeOperators.leafOps.join(', ')}) — deep condition validation is host-owned.` };
  const ruleList = {
    type: 'array',
    maxItems: data.limits.classifyRulesMax,
    items: {
      type: 'object',
      properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, when: conditionNode, note: { type: 'string' } },
      required: ['id', 'when'],
      additionalProperties: false,
    },
  };
  const questionNode = {
    type: 'object',
    properties: {
      id: { type: 'string', pattern: '^[a-z][a-z0-9_]{0,39}$' },
      type: { enum: [...data.pipeline.questions] },
      instructions: { type: 'string' },
      criteria: { type: 'object' },
      options: { type: 'object' },
      levels: { type: 'array', items: { type: 'string' } },
    },
    required: ['id', 'type', 'instructions'],
    additionalProperties: false,
  };
  const reportNode = {
    anyOf: [
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'stat' }, bind: { type: 'string' } }, required: ['id', 'type', 'bind'], additionalProperties: false },
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'table' }, columns: { type: 'array', minItems: 1, items: { type: 'string' } } }, required: ['id', 'type', 'columns'], additionalProperties: false },
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'cards' }, of: { enum: ['items', 'groups'] } }, required: ['id', 'type', 'of'], additionalProperties: false },
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'filter-bar' }, filters: { type: 'array', minItems: 1, items: { type: 'string' } } }, required: ['id', 'type', 'filters'], additionalProperties: false },
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'select' }, bind: { type: 'string' }, options: { type: 'array', minItems: 1, items: { type: 'string' } } }, required: ['id', 'type', 'bind', 'options'], additionalProperties: false },
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'badge' }, bind: { type: 'string' } }, required: ['id', 'type', 'bind'], additionalProperties: false },
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'progress' }, bind: { type: 'string' } }, required: ['id', 'type', 'bind'], additionalProperties: false },
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'actions' }, actions: { type: 'array', minItems: 1, uniqueItems: true, items: { enum: [...data.report.actions.run, ...data.report.actions.item] } } }, required: ['id', 'type', 'actions'], additionalProperties: false },
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'evidence' } }, required: ['id', 'type'], additionalProperties: false },
    ],
  };
  const liveCardNode = {
    anyOf: [
      { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'badge' }, bind: { const: 'run.status' } }, required: ['id', 'type', 'bind'], additionalProperties: false },
      {
        anyOf: [
          { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'stat' }, bind: { enum: data.liveCard.binds.filter((b) => b !== 'progress') } }, required: ['id', 'type', 'bind'], additionalProperties: false },
          { type: 'object', properties: { id: { type: 'string', pattern: NODE_ID_PATTERN }, type: { const: 'progress' }, bind: { const: 'progress' } }, required: ['id', 'type', 'bind'], additionalProperties: false },
        ],
      },
    ],
  };
  const configFieldNode = {
    type: 'object',
    properties: {
      type: { enum: ['string', 'number', 'boolean', 'array'] },
      title: { type: 'string' },
      description: { type: 'string' },
      enum: { type: 'array', minItems: 1 },
      default: {},
      minimum: { type: 'number' },
      maximum: { type: 'number' },
      minLength: { type: 'integer', minimum: 0 },
      maxLength: { type: 'integer', minimum: 0 },
      pattern: { type: 'string' },
      minItems: { type: 'integer', minimum: 0 },
      maxItems: { type: 'integer', minimum: 0 },
      items: {
        type: 'object',
        properties: { type: { enum: ['string'] } },
        additionalProperties: false,
      },
    },
    required: ['type'],
    additionalProperties: false,
  };

  const baseProperties = {
    apiVersion: { type: 'integer', minimum: apiMin, maximum: data.apiVersion.current },
    id: { type: 'string', pattern: data.identity.idPattern },
    version: { type: 'string', pattern: data.identity.versionPattern },
    kind: { enum: Object.keys(data.identity.kind) },
    title: { type: 'string', maxLength: 120 },
    description: { type: 'string', maxLength: data.limits.i18nValueMaxChars },
    author: { type: 'string', minLength: 1, maxLength: 120, $comment: 'Envelope-shared provenance (D25) — rendered verbatim by display/consent surfaces.' },
    license: { type: 'string', minLength: 1, maxLength: 120, $comment: 'Envelope-shared provenance — SPDX identifier preferred or "proprietary"; rendered verbatim.' },
    repository: { type: 'string', maxLength: 512, pattern: repositoryPattern, $comment: 'Envelope-shared provenance — https-only git URL (the family distribution surface is git URLs, D13); no userinfo, no whitespace.' },
    categories: { type: 'array', maxItems: 3, uniqueItems: true, items: { enum: [...categories] }, $comment: 'Envelope-shared closed browse vocabulary (D25) — mirrored from extension-charter.json categories.vocabulary.' },
    docs: { const: data.envelopeSharedFields.docsPointer, $comment: 'Per-extension documentation pointer (plan 34 §10.3): optional; when present, docs/docs-tree.json MUST exist in the bundle and validate against docs-tree.schema.json extensionDocsTree — enforced wherever manifests validate; an invalid tree is a self-disable reason like an invalid manifest.' },
    icon: { type: 'string', maxLength: data.limits.iconMaxBytes, $comment: 'inline raster-only data-URL (png/jpeg/webp) — the byte cap is the real limit; char count is a cheap proxy.' },
    capabilities: { type: 'array', minItems: 1, uniqueItems: true, items: { enum: importedCaps } },
    configSchema: { $ref: '#/$defs/configSchema' },
    defaults: { type: 'object' },
    runParams: { $ref: '#/$defs/configSchema' },
    privacy: { $ref: '#/$defs/privacy' },
    run: { $ref: '#/$defs/pipeline' },
    report: { $ref: '#/$defs/report' },
    liveCard: { $ref: '#/$defs/liveCard' },
    i18n: { $ref: '#/$defs/i18n' },
  };
  const baseRequired = ['apiVersion', 'id', 'version', 'kind', 'capabilities', 'i18n'];

  const bundledExtras = {
    properties: {
      ...baseProperties,
      capabilities: { type: 'array', minItems: 1, uniqueItems: true, items: { enum: allCapIds } },
      contributions: {
        type: 'object',
        propertyNames: { enum: [...data.slots.taxonomy.map((s) => s.id)] },
        additionalProperties: {
          type: 'array',
          items: {
            type: 'object',
            properties: { id: { type: 'string' }, labelKey: { type: 'string' } },
            required: ['id'],
            additionalProperties: false,
          },
        },
      },
      code: {
        type: 'object',
        properties: { entry: { type: 'string' } },
        required: ['entry'],
        additionalProperties: false,
      },
    },
    required: baseRequired,
    additionalProperties: false,
  };

  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: 'https://neuronection.dev/contracts/mini-app-packs.manifest.schema.json',
    title: 'Mini-app pack manifest — imported packs (structural gate)',
    type: 'object',
    properties: baseProperties,
    required: baseRequired,
    additionalProperties: false,
    allOf: [
      {
        if: { properties: { kind: { const: 'assessment' } }, required: ['kind'] },
        then: { required: ['run', 'privacy'] },
      },
      {
        if: { properties: { kind: { const: 'surface' } }, required: ['kind'] },
        then: { properties: { run: false, privacy: false } },
      },
    ],
    $defs: {
      bundledManifest: {
        title: 'Mini-app pack manifest — bundled (Tier 1 code packs)',
        type: 'object',
        ...bundledExtras,
      },
      privacy: {
        type: 'object',
        properties: {
          sendsContent: { type: 'boolean' },
          sensitiveGlobs: { type: 'array', items: { type: 'string' } },
          contentCapBytes: { type: 'integer', minimum: 0 },
        },
        required: ['sendsContent', 'sensitiveGlobs'],
        additionalProperties: false,
      },
      i18n: {
        type: 'object',
        properties: {
          defaultLocale: { type: 'string', pattern: LOCALE_PATTERN },
          locales: {
            type: 'object',
            maxProperties: data.limits.localesMax,
            additionalProperties: {
              type: 'object',
              maxProperties: data.limits.i18nKeysPerLocaleMax,
              additionalProperties: { type: 'string', maxLength: data.limits.i18nValueMaxChars },
            },
          },
        },
        required: ['defaultLocale', 'locales'],
        additionalProperties: false,
      },
      configSchema: {
        type: 'object',
        properties: {
          type: { const: 'object' },
          properties: {
            type: 'object',
            maxProperties: data.limits.configPropertiesMax,
            additionalProperties: configFieldNode,
          },
        },
        required: ['type', 'properties'],
        additionalProperties: false,
        $comment: `Depth cap (${data.limits.configDepthMax}) is host-owned.`,
      },
      pipeline: {
        type: 'object',
        properties: {
          scan: {
            type: 'object',
            properties: {
              includeHidden: { type: 'boolean' },
              excludeGlobs: { type: 'array', items: { type: 'string' } },
              fileCap: { type: 'integer', minimum: 1, maximum: data.limits.scanFileCapHard },
              maxDepth: { type: 'integer', minimum: 1, maximum: data.limits.scanDepthHard },
            },
            additionalProperties: false,
          },
          classify: {
            type: 'object',
            properties: { keep: ruleList, ask: ruleList, candidate: ruleList, veto: ruleList },
            additionalProperties: false,
          },
          decide: {
            type: 'object',
            properties: {
              questions: { type: 'array', maxItems: data.limits.questionsPerPackMax, items: questionNode },
              readContext: { type: 'boolean' },
              readContextWhen: conditionNode,
            },
            additionalProperties: false,
          },
          compose: {
            type: 'object',
            properties: { keepWhen: conditionNode, candidateWhen: conditionNode, askWhen: conditionNode },
            additionalProperties: false,
          },
          report: { $ref: '#/$defs/report' },
          propose: {
            type: 'object',
            properties: {
              verb: { enum: [...data.pipeline.proposeVerbs] },
              groupBy: { type: 'string' },
              gate: {
                type: 'object',
                properties: { minConfidence: { type: 'number', minimum: 0, maximum: 1 } },
                required: ['minConfidence'],
                additionalProperties: false,
              },
            },
            required: ['verb', 'gate'],
            additionalProperties: false,
          },
        },
        additionalProperties: false,
        $comment: `Which steps are required/optional (decide, propose) and their cross-references are host-owned.`,
      },
      report: {
        type: 'object',
        properties: { nodes: { type: 'array', minItems: 1, maxItems: data.limits.reportComponentsMax, items: reportNode } },
        required: ['nodes'],
        additionalProperties: false,
      },
      liveCard: {
        type: 'object',
        properties: { nodes: { type: 'array', minItems: 1, maxItems: data.limits.liveCardComponentsMax, items: liveCardNode } },
        required: ['nodes'],
        additionalProperties: false,
      },
    },
    $comment: [
      'STRUCTURAL GATE ONLY — a manifest passing this schema is NOT "valid".',
      'The host-neutral rules below are validator-owned; every host must port them and the desktop validator (src/shared/app-pack/validate.ts) stays normative for behavior disputes:',
      '1. cross-reference validation (compose referencing undeclared rule/question ids, propose verb vs run:arm actions, duplicate capability entries, duplicate node/rule/question ids);',
      '2. i18n completeness (required key sets: title, description, config.*, report.<id>/live.<id> per node, rule.* ids — identical across every locale);',
      '3. privacy lint (sensitiveGlob syntax, host-sensitive BASELINE union — rule:host-sensitive outranks pack rules);',
      '4. capability semantics (fs-read/run required for assessment, fs-write-quarantine requires propose, propose requires gate confidence, ui/ui:custom-code bundled-only, reserved ids host-/neuro-);',
      '5. evidence-node mandatory wherever table/cards render recommendations;',
      '6. fingerprint/verdict-cache and budget semantics (plan 26 S3).',
      `Locale syntax: ${LOCALE_PATTERN}; component/rule node ids: ${NODE_ID_PATTERN} (validator-owned, mirrored here).`,
    ].join(' '),
  };
}
