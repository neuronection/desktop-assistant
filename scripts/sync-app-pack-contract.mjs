#!/usr/bin/env node
// sync-app-pack-contract — generate the mini-app pack contract module from the
// canonical JSON (single source, ADR-0029 / plan 26 S1).
// Master: dev/scripts/sync-app-pack-contract.mjs (vendored copies stay
// byte-identical). Reads contracts/mini-app-packs.json NEXT TO ITSELF.
//
// Usage:
//   node sync-app-pack-contract.mjs --ts <out.ts>     write the TypeScript module
//   node sync-app-pack-contract.mjs --check <ts-path> compare generated TS to disk (exit 1 on drift)
// Unknown "schema" versions are refused (exit 2).

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const canonicalPath = join(here, '..', 'contracts', 'mini-app-packs.json');

const SUPPORTED_SCHEMA = 1;

function fail(code, message) {
  console.error(`sync-app-pack-contract: ${message}`);
  process.exit(code);
}

if (!existsSync(canonicalPath)) {
  fail(2, `canonical file not found at ${canonicalPath}`);
}
const data = JSON.parse(readFileSync(canonicalPath, 'utf8'));
if (data.schema !== SUPPORTED_SCHEMA || data.contract !== 'mini-app-packs') {
  fail(2, `unsupported contract file (schema ${data.schema}, contract ${data.contract})`);
}

const capIds = data.capabilities.map((c) => c.id);
if (new Set(capIds).size !== capIds.length) fail(2, 'duplicate capability ids');
const slotIds = data.slots.taxonomy.map((s) => s.id);
if (new Set(slotIds).size !== slotIds.length) fail(2, 'duplicate slot ids');

function list(name, value) {
  if (!Array.isArray(value) || value.length === 0 || !value.every((v) => typeof v === 'string')) {
    fail(2, `${name} must be a non-empty string array`);
  }
  return value;
}

const caps = data.capabilities.map((c) => {
  if (!Array.isArray(c.tiers) || !c.tiers.every((t) => typeof t === 'number')) {
    fail(2, `capability ${c.id} tiers must be a number array`);
  }
  return { id: c.id, tiers: c.tiers };
});

const leafOps = list('composeOperators.leafOps', data.pipeline.composeOperators.leafOps);
const composites = list('composeOperators.conditions', data.pipeline.composeOperators.conditions).filter((c) => c !== 'leaf');

const ts = `// GENERATED by sync-app-pack-contract — do not edit.
// Source: contracts/mini-app-packs.json (family canonical: dev/contracts/).
// Regenerate: node scripts/sync-app-pack-contract.mjs --ts src/shared/app-pack/contract.generated.ts

export const PACK_API_VERSION = ${data.apiVersion.current} as const;
export const PACK_DEPRECATION_WINDOW_MAJORS = ${data.apiVersion.deprecationWindowMajors} as const;

export const PACK_KINDS = ${JSON.stringify(list('identity.kind', Object.keys(data.identity.kind)))} as const;
export const PACK_ID_PATTERN = ${JSON.stringify(data.identity.idPattern)};
export const PACK_VERSION_PATTERN = ${JSON.stringify(data.identity.versionPattern)};
export const PACK_RESERVED_ID_PREFIXES = ${JSON.stringify(list('identity.reservedIdPrefixes', data.identity.reservedIdPrefixes))} as const;

export const PACK_CAPABILITIES = ${JSON.stringify(capIds)} as const;
export const PACK_CAPABILITY_TIERS: Readonly<Record<string, readonly number[]>> = {
${caps.map((c) => `  ${JSON.stringify(c.id)}: ${JSON.stringify(c.tiers)},`).join('\n')}
};

export const PACK_SLOTS = ${JSON.stringify(slotIds)} as const;

export const PACK_STEPS = ${JSON.stringify(list('pipeline.steps', data.pipeline.steps))} as const;
export const PACK_PROPOSE_VERBS = ${JSON.stringify(list('pipeline.proposeVerbs', data.pipeline.proposeVerbs))} as const;
export const PACK_VERDICTS = ${JSON.stringify(list('pipeline.verdicts', data.pipeline.verdicts))} as const;
export const PACK_QUESTION_TYPES = ${JSON.stringify(list('pipeline.questions', data.pipeline.questions))} as const;
export const PACK_RUN_STATUSES = ${JSON.stringify(list('pipeline.run.statuses', data.pipeline.run.statuses))} as const;
export const PACK_RUN_EVENTS = ${JSON.stringify(list('pipeline.run.events', data.pipeline.run.events))} as const;
export const PACK_ITEM_STATES = ${JSON.stringify(list('pipeline.run.itemStates', data.pipeline.run.itemStates))} as const;
export const PACK_CONDITION_COMPOSITES = ${JSON.stringify(composites)} as const;
export const PACK_LEAF_OPS = ${JSON.stringify(leafOps)} as const;

export const PACK_REPORT_COMPONENTS = ${JSON.stringify(list('report.components', data.report.components))} as const;
export const PACK_RUN_ACTIONS = ${JSON.stringify(list('report.actions.run', data.report.actions.run))} as const;
export const PACK_ITEM_ACTIONS = ${JSON.stringify(list('report.actions.item', data.report.actions.item))} as const;
export const PACK_EXPORT_FORMATS = ${JSON.stringify(list('report.exportFormats', data.report.exportFormats))} as const;

export const PACK_ERROR_CODES = ${JSON.stringify(data.errors.codes.map((e) => e.code))} as const;

export const PACK_HOST_SENSITIVE_BASELINE = ${JSON.stringify(list('privacy.hostBaselineGlobs', data.privacy.hostBaselineGlobs))} as const;

export const PACK_REFUSED_ROOTS_EXACT = ${JSON.stringify(data.fs.refusedRoots.exact)} as const;
export const PACK_REFUSED_ROOTS_PREFIX = ${JSON.stringify(data.fs.refusedRoots.prefix)} as const;

export const PACK_LIMITS = ${JSON.stringify(data.limits, null, 2)} as const;
`;

const [, , mode, target] = process.argv;
if (mode === '--ts') {
  if (!target) fail(2, '--ts requires an output path');
  writeFileSync(target, ts, 'utf8');
  console.log(`sync-app-pack-contract: wrote ${target} (${capIds.length} capabilities, ${slotIds.length} slots)`);
} else if (mode === '--check') {
  if (!target) fail(2, '--check requires a path');
  if (!existsSync(target)) fail(1, `generated file missing: ${target}`);
  const onDisk = readFileSync(target, 'utf8');
  if (onDisk !== ts) {
    fail(1, `drift detected in ${target} — regenerate with: node scripts/sync-app-pack-contract.mjs --ts ${target}`);
  }
  console.log('sync-app-pack-contract: no drift');
} else {
  fail(2, 'usage: sync-app-pack-contract.mjs --ts <out.ts> | --check <ts-path>');
}
